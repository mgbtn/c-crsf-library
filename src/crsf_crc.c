uint8_t crsf_crc8(const uint8_t *data, size_t len) {
    uint8_t crc = 0x00;
    
    for (size_t i = 0; i < len; i++) {
        crc ^= data[i];
        for (int j = 0; j < 8; j++) {
            if (crc & 0x80) {
                crc = (crc << 1) ^ 0xD5;
            } else {
                crc = crc << 1;
            }
        }
    }
    
    return crc;
}